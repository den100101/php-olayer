-- Database: db_website
CREATE DATABASE IF NOT EXISTS db_website CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE db_website;

CREATE TABLE IF NOT EXISTS tbl_account (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    USERNAME VARCHAR(100) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    USERTYPE ENUM('Admin','Registrar','Dean','Instructor','Student') NOT NULL DEFAULT 'Student',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tbl_course (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    COURSE_CODE VARCHAR(30) NOT NULL UNIQUE,
    COURSE_NAME VARCHAR(150) NOT NULL,
    UNITS TINYINT UNSIGNED NOT NULL DEFAULT 3
);

CREATE TABLE IF NOT EXISTS tbl_instructors (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    SALUTATION VARCHAR(20) NOT NULL,
    FIRSTNAME VARCHAR(100) NOT NULL,
    MIDDLENAME VARCHAR(100) NULL,
    LASTNAME VARCHAR(100) NOT NULL,
    PHOTO VARCHAR(255) NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Placeholder tables for the remaining pages in the assignment.
CREATE TABLE IF NOT EXISTS tbl_term (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    TERM_NAME VARCHAR(100) NOT NULL,
    STATUS VARCHAR(30) DEFAULT 'Active'
